// Regenerates src/runtimes/catalog.js from Radium's runtime registry.
// Usage: node scripts/sync-catalog.mjs <path to Radium>/src-tauri/src/core/runtimes/registry.rs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "runtimes", "catalog.js");
const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/sync-catalog.mjs <registry.rs>");
  process.exit(1);
}

const src = readFileSync(source, "utf8");
const snake = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const last = (path) => path.trim().split("::").pop();

// Named constants: lists (`const X: &[C] = &[...]`), platforms, licences.
const lists = {};
for (const m of src.matchAll(/const (\w+): &\[(?:C|F|A|&str)\] = &\[([\s\S]*?)\];/g)) {
  lists[m[1]] = m[2].split(",").map((s) => s.trim()).filter(Boolean);
}
const structs = {};
for (const m of src.matchAll(/const (\w+): (?:Platforms|License) = \w+ \{([\s\S]*?)\};/g)) {
  const fields = {};
  for (const f of m[2].matchAll(/(\w+): ([^,]+),/g)) fields[f[1]] = f[2].trim();
  structs[m[1]] = fields;
}

function list(value) {
  value = value.trim();
  const items = value.startsWith("&[") ? value.slice(2, -1).split(",").map((s) => s.trim()).filter(Boolean) : lists[value];
  if (!items) throw new Error(`unknown list ${value}`);
  return items.map((item) => (item.startsWith('"') ? item.slice(1, -1) : snake(last(item))));
}

function field(block, key) {
  const m = block.match(new RegExp(`\\n        ${key}: ([\\s\\S]*?),\\n        \\w+:`));
  return m ? m[1].trim() : undefined;
}

const body = src.slice(src.indexOf("pub static RUNTIMES"));
const blocks = body.split("\n    RuntimeDescriptor {").slice(1).map((b) => b.slice(0, b.indexOf("\n    },")) + "\n        end: x,");

const runtimes = blocks.map((b) => {
  const str = (k) => JSON.parse(field(b, k));
  const platforms = structs[field(b, "platforms")];
  const license = structs[field(b, "license")];
  const port = field(b, "default_port");
  const telemetry = field(b, "telemetry") ?? "";
  const prom = telemetry.match(/Prometheus \{\s*path: "([^"]+)",\s*prefix: "([^"]+)",\s*needs_flag: (None|Some\("([^"]+)"\)),/);
  return {
    id: str("id"),
    name: str("name"),
    group: snake(last(field(b, "group"))),
    tier: snake(last(field(b, "tier"))),
    mode: snake(last(field(b, "mode"))),
    layer: snake(last(field(b, "layer"))),
    wraps: list(field(b, "wraps")),
    capabilities: list(field(b, "capabilities")),
    formats: list(field(b, "formats")),
    apis: list(field(b, "apis")),
    defaultPort: port === "None" ? null : Number(port.match(/\d+/)[0]),
    windows: snake(last(platforms.windows)),
    prometheus: prom ? { path: prom[1], prefix: prom[2], needsFlag: prom[4] ?? null } : null,
    license: { spdx: JSON.parse(license.spdx), class: snake(last(license.class)) },
    maintenance: snake(last(field(b, "maintenance"))),
    note: str("note"),
    verified: field(b, "verified") === "true",
    sourceUrl: str("source_url"),
  };
});

const header = `// GENERATED by scripts/sync-catalog.mjs from Radium src-tauri/src/core/runtimes/registry.rs. Do not edit by hand.
// ${runtimes.length} runtimes. Data only: nothing here starts, downloads or connects to anything.
"use strict";

const RUNTIMES = Object.freeze(${JSON.stringify(runtimes, null, 2)});

function find(id) {
  return RUNTIMES.find((runtime) => runtime.id === id);
}

module.exports = { RUNTIMES, find };
`;
writeFileSync(out, header);
console.log(`wrote ${runtimes.length} runtimes to ${out}`);
